//! USB HID usages and the Windows virtual-key / macOS virtual-keycode tables.
//! The wire never carries an OS-specific code.

/// Letters, digits, modifiers, arrows, function keys, and editing keys.
pub fn vk_to_hid(vk: u16) -> Option<u16> {
    hid_from_vk(vk)
}

pub fn hid_to_vk(hid: u16) -> Option<u16> {
    VK_FROM_HID
        .iter()
        .find(|(h, _)| *h == hid)
        .map(|(_, vk)| *vk)
}

pub fn mac_to_hid(keycode: u16) -> Option<u16> {
    MAC.iter()
        .find(|(_, mac, _)| *mac == keycode)
        .map(|(hid, _, _)| *hid)
}

pub fn hid_to_mac(hid: u16) -> Option<u16> {
    MAC.iter()
        .find(|(h, _, _)| *h == hid)
        .map(|(_, mac, _)| *mac)
}

fn hid_from_vk(vk: u16) -> Option<u16> {
    MAC.iter()
        .find(|(_, _, v)| *v == vk)
        .map(|(hid, _, _)| *hid)
}

