#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_digits_and_modifiers_round_trip() {
        for vk in [
            0x41_u16, 0x43, 0x5A, 0x31, 0x39, 0xA2, 0x5B, 0xA4, 0x1B, 0x25, 0x27, 0x91,
        ] {
            let hid = vk_to_hid(vk).unwrap_or_else(|| panic!("vk {vk:#x}"));
            assert_eq!(hid_to_vk(hid), Some(vk), "hid {hid:#x}");
        }
    }

    #[test]
    fn mac_command_and_option_map_to_gui_and_alt() {
        // kVK_Command = 0x37 -> HID GUI, kVK_Option = 0x3A -> HID Alt.
        assert_eq!(mac_to_hid(0x37), Some(0xE3));
        assert_eq!(mac_to_hid(0x3A), Some(0xE2));
        assert_eq!(mac_to_hid(0x00), Some(0x04)); // A
        assert_eq!(hid_to_mac(0x04), Some(0x00));
        assert_eq!(hid_to_mac(0xE3), Some(0x37));
    }

    #[test]
    fn copy_shortcut_keys_exist_on_both_tables() {
        let c = vk_to_hid(0x43).unwrap();
        let ctrl = vk_to_hid(0xA2).unwrap();
        assert_eq!(c, 0x06);
        assert_eq!(ctrl, 0xE0);
        assert!(mac_to_hid(0x08).is_some());
    }
}
