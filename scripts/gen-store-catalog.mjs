#!/usr/bin/env node
// Writes src/agent_store/embedded.rs: the list of Agent Store catalog files the app embeds.
//
// Every file under <root>/catalog/agents/<id>/ with a .toml, .txt or .jsonl extension is
// listed as (relative path, include_str!(...)). The app then has the catalog text inside
// the binary, with no download and no run-time file reads.
//
//   node scripts/gen-store-catalog.mjs                 write embedded.rs
//   node scripts/gen-store-catalog.mjs --check         exit 1 when embedded.rs is out of date
//   node scripts/gen-store-catalog.mjs --root <dir>    use another tree (the tests do this)
//
// <root> is the folder that holds catalog/ and src/ (default: packages/app/src-tauri).

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_ROOT = join(repoRoot, 'packages', 'app', 'src-tauri');

// Only these files are embedded. Anything else in an agent folder (notes, images) is skipped.
const EXTENSIONS = ['.toml', '.txt', '.jsonl'];
// Names become part of an include_str! path, so only plain characters are allowed.
const SAFE_NAME = /^[A-Za-z0-9_.-]+$/;

// Returns the embedded paths relative to <root>/catalog, forward slashes, sorted by code unit.
// A missing catalog/agents folder is an empty catalog, not an error.
export function listCatalogFiles(root) {
  const agents = join(root, 'catalog', 'agents');
  if (!existsSync(agents)) return [];
  const found = [];
  const walk = (dir, rel) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      const relPath = `${rel}/${name}`;
      if (statSync(full).isDirectory()) {
        assertSafeName(name, relPath);
        walk(full, relPath);
      } else if (EXTENSIONS.some((ext) => name.endsWith(ext))) {
        assertSafeName(name, relPath);
        found.push(relPath);
      }
    }
  };
  walk(agents, 'agents');
  return found.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function assertSafeName(name, relPath) {
  if (!SAFE_NAME.test(name)) {
    throw new Error(`catalog name not allowed (use letters, digits, _ . -): ${relPath}`);
  }
}

// The Rust file for a list of catalog paths. Each path is safe (assertSafeName), so no escaping.
export function renderEmbedded(files) {
  const header = [
    '//! GENERATED by scripts/gen-store-catalog.mjs. Do not edit by hand.',
    '//! Lists every Agent Store catalog file the app embeds. Run the script after a catalog change.',
    '',
  ];
  if (files.length === 0) {
    return [...header, '#[rustfmt::skip]', 'pub static FILES: &[(&str, &str)] = &[];', ''].join('\n');
  }
  const rows = files.map((f) => `    ("${f}", include_str!("../../catalog/${f}")),`);
  return [...header, '#[rustfmt::skip]', 'pub static FILES: &[(&str, &str)] = &[', ...rows, '];', ''].join('\n');
}

export function embeddedPath(root) {
  return join(root, 'src', 'agent_store', 'embedded.rs');
}

// Compares the file on disk with what the generator would write. CRLF is treated as LF,
// so a Windows checkout with autocrlf still passes.
export function isUpToDate(root, text) {
  const target = embeddedPath(root);
  if (!existsSync(target)) return false;
  return readFileSync(target, 'utf8').replace(/\r\n/g, '\n') === text;
}

function parseArgs(argv) {
  const opts = { root: DEFAULT_ROOT, check: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--root') {
      i += 1;
      if (!argv[i]) throw new Error('--root needs a folder');
      opts.root = argv[i];
    } else throw new Error(`unknown option: ${arg}`);
  }
  return opts;
}

export function main(argv) {
  let opts;
  try {
    opts = parseArgs(argv);
  } catch (err) {
    console.error(err.message);
    return 2;
  }
  const root = resolve(opts.root);
  const target = embeddedPath(root);
  const shown = relative(root, target).split('\\').join('/');
  try {
    const files = listCatalogFiles(root);
    const text = renderEmbedded(files);
    if (opts.check) {
      if (!isUpToDate(root, text)) {
        console.error(`${shown} is out of date. Run: node scripts/gen-store-catalog.mjs`);
        return 1;
      }
      console.log(`${shown} is up to date (${files.length} catalog files).`);
      return 0;
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    console.log(`wrote ${shown} (${files.length} catalog files).`);
    return 0;
  } catch (err) {
    console.error(err.message);
    return 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
