// node --test scripts/package-check/popular.test.mjs
// Parse and normalize helpers on inline samples (no network), plus a check of the three list files
// the app embeds (SPEC-n33 S14: every name passes the shape rule, no duplicates, header present, size cap).
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import {
  RULES,
  buildList,
  namesFromCratesJson,
  namesFromPypiJson,
  namesFromText,
  normalize,
  renderFile,
  validName,
} from './popular.mjs';

const LIST_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
  'packages',
  'app',
  'src-tauri',
  'src',
  'prompt_risk',
  'packages',
  'popular',
);

test('normalize: npm lowercases, PyPI is PEP 503, crates maps _ to -', () => {
  assert.equal(normalize('npm', 'Lodash'), 'lodash');
  assert.equal(normalize('npm', '@Types/Node'), '@types/node');
  assert.equal(normalize('pypi', 'Foo.Bar_baz'), 'foo-bar-baz');
  assert.equal(normalize('pypi', 'Foo__Bar..x'), 'foo-bar-x');
  assert.equal(normalize('crates', 'Serde_JSON'), 'serde-json');
});

test('validName: good and bad names per ecosystem', () => {
  for (const name of ['lodash', 'react-dom', '@types/node', 'a.b_c~d']) assert.ok(validName('npm', name), name);
  for (const name of ['../x', 'a b', 'x'.repeat(215), '@scope', '']) assert.ok(!validName('npm', name), name);
  for (const name of ['requests', 'typing-extensions', 'a']) assert.ok(validName('pypi', name), name);
  for (const name of ['a/b', '-x', 'x-', 'x'.repeat(101)]) assert.ok(!validName('pypi', name), name);
  for (const name of ['serde', 'tokio-util', 'serde_json']) assert.ok(validName('crates', name), name);
  for (const name of ['1abc', 'a'.repeat(65), 'a.b']) assert.ok(!validName('crates', name), name);
});

test('namesFromText: quoted tokens without spaces, shape checked by buildList', () => {
  const text = 'export const list = ["lodash", \'@babel/core\', `react`, "not a name", "", "Bad/Name!", "lodash"];';
  assert.deepEqual(namesFromText(text), ['lodash', '@babel/core', 'react', 'Bad/Name!', 'lodash']);
  assert.deepEqual(buildList('npm', namesFromText(text)), ['lodash', '@babel/core', 'react']);
});

test('namesFromPypiJson and namesFromCratesJson read the feed shapes', () => {
  assert.deepEqual(
    namesFromPypiJson({ last_update: '2026-10-01', rows: [{ project: 'boto3', download_count: 9 }, { project: 'numpy' }] }),
    ['boto3', 'numpy'],
  );
  assert.deepEqual(namesFromPypiJson({}), []);
  assert.deepEqual(namesFromCratesJson({ crates: [{ name: 'serde' }, { name: 'tokio' }] }), ['serde', 'tokio']);
  assert.deepEqual(namesFromCratesJson({ crates: [{ id: 1 }] }), []);
});

test('buildList: normalizes, drops invalid, dedupes keeping rank order, caps at the limit', () => {
  assert.deepEqual(buildList('pypi', ['Requests', 'requests', 'Flask', 'bad/name', 'x_y']), ['requests', 'flask', 'x-y']);
  assert.deepEqual(buildList('crates', ['Serde', 'serde_json', 'serde-json', '9bad']), ['serde', 'serde-json']);
  const many = Array.from({ length: RULES.crates.limit + 5 }, (_, i) => `crate${i}`);
  assert.equal(buildList('crates', many).length, RULES.crates.limit);
});

test('renderFile: header lines, count matches, optional note, LF ending', () => {
  const text = renderFile({ source: 'https://example.invalid/list', fetched: '2026-10-29', names: ['a1', 'b2'] });
  assert.equal(
    text,
    [
      '# Package check top list (SPEC-n33 section 3.3). Generated by scripts/package-check/popular.mjs.',
      '# source: https://example.invalid/list',
      '# fetched: 2026-10-29',
      '# count: 2',
      'a1',
      'b2',
      '',
    ].join('\n'),
  );
  const noted = renderFile({ source: 's', fetched: 'f', note: 'primary feed failed', names: [] });
  assert.match(noted, /# note: primary feed failed\n$/);
});

for (const eco of Object.keys(RULES)) {
  test(`list file ${eco}.txt: header, shape, normalized, unique, size cap`, () => {
    const text = readFileSync(join(LIST_DIR, `${eco}.txt`), 'utf8');
    assert.ok(!text.includes('\r'), 'LF only');
    const lines = text.split('\n');
    assert.ok(lines[0].startsWith('# '), 'header first');
    const header = lines.filter((l) => l.startsWith('# '));
    for (const key of ['# source: ', '# fetched: ', '# count: ']) {
      assert.ok(header.some((l) => l.startsWith(key)), `header has ${key}`);
    }
    const names = lines.filter((l) => l !== '' && !l.startsWith('#'));
    const count = Number(header.find((l) => l.startsWith('# count: ')).slice('# count: '.length));
    assert.equal(count, names.length, 'count matches the name lines');
    assert.ok(names.length <= RULES[eco].limit, 'size cap');
    assert.equal(new Set(names).size, names.length, 'no duplicates');
    for (const name of names) {
      assert.ok(validName(eco, name), `valid shape: ${name}`);
      assert.equal(normalize(eco, name), name, `already normalized: ${name}`);
    }
  });
}
